#!/bin/sh
# Generates the credentials the stack needs, in two places:
#
#   .env           read by docker compose (db container + server container)
#   server/config  read by ./matCha when it runs outside Docker
#
# .env is the source of truth and is created once with random values; re-runs
# keep it as it is. server/config is always re-rendered from it, so editing a
# credential means editing .env and running this again.
#
# Both files are gitignored. Nothing here is ever committed.
set -e

cd "$(dirname "$0")/.."

ENV_FILE=.env
CONFIG_FILE=server/config
CONFIG_TEMPLATE=server/config.example

random_hex() {
    openssl rand -hex "$1"
}

if [ -f "$ENV_FILE" ]; then
    echo "$ENV_FILE already exists, keeping it."
else
    cat > "$ENV_FILE" <<EOF
# Generated by 'make secrets' on $(date -u '+%Y-%m-%d %H:%M:%SZ').
# Gitignored. Edit freely, then re-run 'make secrets' to update server/config.
DB_USER=matcha
DB_PASSWORD=$(random_hex 18)
DB_NAME=matcha_db
TOKEN_SECRET=$(random_hex 32)
EOF
    chmod 600 "$ENV_FILE"
    echo "Wrote $ENV_FILE with freshly generated credentials."
fi

# shellcheck disable=SC1090
. "./$ENV_FILE"

for var in DB_USER DB_PASSWORD DB_NAME TOKEN_SECRET; do
    eval "val=\$$var"
    if [ -z "$val" ]; then
        echo "$ENV_FILE: $var is empty. Fill it in, or delete $ENV_FILE and re-run." >&2
        exit 1
    fi
done

sed -e "s|^DB_USER=.*|DB_USER=$DB_USER|" \
    -e "s|^DB_PASSWORD=.*|DB_PASSWORD=$DB_PASSWORD|" \
    -e "s|^DB_NAME=.*|DB_NAME=$DB_NAME|" \
    -e "s|^TOKEN_SECRET=.*|TOKEN_SECRET=$TOKEN_SECRET|" \
    "$CONFIG_TEMPLATE" > "$CONFIG_FILE"
chmod 600 "$CONFIG_FILE"
echo "Rendered $CONFIG_FILE from $ENV_FILE."
